#[test]
fn smooth_knn_dist_matches_python() {
    let knn_dists = ndarray::Array2::from_shape_fn((N, NN), |(i, j)| KNN_DISTS[i][j] as f32);
    let (sigmas, rhos) = smooth_knn_dist(&knn_dists, 5.0, 64, 1.0, 1.0);
    for i in 0..N {
        let got = f64::from(sigmas[i]);
        let want = SIGMAS[i];
        assert!(
            (got - want).abs() <= 1e-6 * want.abs().max(1.0),
            "sigma[{i}]: got {got}, want {want}"
        );
        let got = f64::from(rhos[i]);
        let want = RHOS[i];
        assert!(
            (got - want).abs() <= 1e-6 * want.abs().max(1.0),
            "rho[{i}]: got {got}, want {want}"
        );
    }
}

#[test]
fn fuzzy_simplicial_set_matches_python() {
    let knn_indices = ndarray::Array2::from_shape_fn((N, NN), |(i, j)| KNN_INDICES[i][j]);
    let knn_dists = ndarray::Array2::from_shape_fn((N, NN), |(i, j)| KNN_DISTS[i][j] as f32);
    let (graph, _sigmas, _rhos, dists) =
        fuzzy_simplicial_set(N, NN, &knn_indices, &knn_dists, 1.0, 1.0, true, true)
            .expect("fuzzy set");
    assert_eq!(graph.data.len(), GRAPH_DATA.len());
    for idx in 0..GRAPH_DATA.len() {
        assert_eq!(graph.indices[idx], GRAPH_COL[idx], "col {idx}");
        let got = f64::from(graph.data[idx]);
        let want = GRAPH_DATA[idx];
        assert!(
            (got - want).abs() <= 1e-5 * want.abs().max(1.0),
            "graph[{idx}]: got {got}, want {want}"
        );
    }
    let d = dists.expect("dists");
    assert_eq!(d.data.len(), DISTS_DATA.len());
    for (idx, &want) in DISTS_DATA.iter().enumerate() {
        let got = f64::from(d.data[idx]);
        assert!(
            (got - want).abs() <= 1e-6,
            "dists[{idx}]: got {got}, want {want}"
        );
    }
}
