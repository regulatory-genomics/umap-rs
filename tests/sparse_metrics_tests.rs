#[test]
fn test_arr_union_copies_nonempty_input() {
    // Python: test_arr_union_copies_nonempty_input
    let indices = [0, 2];
    assert_eq!(arr_union(&[], &indices), vec![0, 2]);
    assert_eq!(arr_union(&indices, &[]), vec![0, 2]);
    // union sorts and dedups
    assert_eq!(arr_union(&[3, 1], &[2, 1]), vec![1, 2, 3]);
}

#[test]
fn test_arr_intersect() {
    assert_eq!(arr_intersect(&[0, 2], &[0, 2]), vec![0, 2]);
    assert_eq!(arr_intersect(&[0, 2], &[1, 3]), Vec::<i32>::new());
    // Python's simplified intersect keeps one entry per adjacent equal pair
    // in the sorted concatenation (multiset-like semantics), unlike
    // numpy.intersect1d which dedups first.
    assert_eq!(arr_intersect(&[0, 0, 2], &[0, 2, 2]), vec![0, 0, 2, 2]);
}

