#[test]
fn test_general_sset_intersection_leaves_unmatched_entries() {
    // Entries absent from both left and right rows keep their pre-filled
    // value (the numba kernel only overwrites where the mixing condition
    // holds).
    let left = CsrMatrix {
        shape: (1, 4),
        indptr: vec![0, 2],
        indices: vec![0, 1],
        data: vec![0.5, 0.7],
    };
    let right = CsrMatrix {
        shape: (1, 4),
        indptr: vec![0, 2],
        indices: vec![0, 1],
        data: vec![0.2, 0.9],
    };
    let mut data = [7.0f32, 7.0];
    general_sset_intersection(
        &left.indptr,
        &left.indices,
        &left.data,
        &right.indptr,
        &right.indices,
        &right.data,
        &[0, 0],
        &[2, 3],
        &mut data,
        0.5,
        false,
    );
    assert_eq!(data, [7.0, 7.0]);
}

#[test]
fn test_general_sset_robust_to_out_of_range_row() {
    // Python would raise IndexError for a result row beyond indptr; the Rust
    // kernel must not panic (it simply leaves the entry untouched).
    let left = CsrMatrix {
        shape: (1, 4),
        indptr: vec![0, 2],
        indices: vec![0, 1],
        data: vec![0.5, 0.7],
    };
    let right = CsrMatrix {
        shape: (1, 4),
        indptr: vec![0, 2],
        indices: vec![0, 1],
        data: vec![0.2, 0.9],
    };
    let mut data = [7.0f32, 7.0];
    general_sset_intersection(
        &left.indptr,
        &left.indices,
        &left.data,
        &right.indptr,
        &right.indices,
        &right.data,
        &[5, 5],
        &[2, 3],
        &mut data,
        0.5,
        false,
    );
    general_sset_union(
        &left.indptr,
        &left.indices,
        &left.data,
        &right.indptr,
        &right.indices,
        &right.data,
        &[5, 5],
        &[2, 3],
        &mut data,
    );
    // intersection leaves the entry untouched; union unconditionally writes
    // (like Python), falling back to the minimum floors:
    // 0.25 + 0.1 - 0.25 * 0.1 = 0.325
    assert_eq!(data, [0.325, 0.325]);
}

