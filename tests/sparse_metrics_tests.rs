/// Resolve a named sparse metric and call it.
fn call(metric: &str, a: (&[i32], &[f32]), b: (&[i32], &[f32]), kwds: &[f32]) -> f32 {
    sparse_named_distances(metric).unwrap_or_else(|| panic!("unknown sparse metric: {metric}"))(
        a.0, a.1, b.0, b.1, kwds,
    )
}

/// Compare against a Python-generated f64 reference with f32 tolerance.
fn assert_close(actual: f32, expected: f64) {
    assert_relative_eq!(actual, expected as f32, epsilon = 1e-6, max_relative = 1e-5);
}

/// The small CSR pair used by the sset kernel tests, plus the result COO
/// (pre-filled with zeros on the union sparsity).
fn sset_inputs() -> (CsrMatrix, CsrMatrix, CooMatrix) {
    let left = CsrMatrix {
        shape: (3, 5),
        indptr: vec![0, 3, 5, 5], // row 2 is empty
        indices: vec![0, 2, 4, 1, 3],
        data: vec![0.1, 0.5, 0.9, 0.3, 0.7],
    };
    let right = CsrMatrix {
        shape: (3, 5),
        indptr: vec![0, 2, 5, 7],
        indices: vec![1, 2, 0, 2, 3, 2, 4],
        data: vec![0.4, 0.6, 0.2, 0.8, 0.5, 0.3, 0.7],
    };
    let result = CooMatrix {
        shape: (3, 5),
        row: SSET_ROWS.to_vec(),
        col: SSET_COLS.to_vec(),
        data: vec![0.0; 10],
    };
    (left, right, result)
}

