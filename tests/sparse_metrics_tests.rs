#[test]
fn test_metric_aliases() {
    let aliases = [
        ("l1", "manhattan"),
        ("taxicab", "manhattan"),
        ("linf", "chebyshev"),
        ("linfty", "chebyshev"),
        ("linfinity", "chebyshev"),
    ];
    for (alias, canonical) in aliases {
        assert!(sparse_named_distances(alias).is_some(), "alias: {alias}");
        // aliases resolve to the same behaviour as their canonical metric
        assert_eq!(
            call(alias, F0, F1, &[]),
            call(canonical, F0, F1, &[]),
            "alias: {alias}"
        );
    }
    // aliases resolve to distinct behaviour per family
    assert_close(call("l1", F0, F1, &[]), 12.5);
    assert_close(call("linf", F0, F1, &[]), 3.5);
}

