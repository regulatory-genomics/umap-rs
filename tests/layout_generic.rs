// Python: umap.distances.manhattan / manhattan_grad (port for the test).
fn manhattan(x: &[f32], y: &[f32], _args: &[f32]) -> f32 {
    let mut result = 0.0f32;
    for i in 0..x.len() {
        result += (x[i] - y[i]).abs();
    }
    result
}

fn manhattan_grad(x: &[f32], y: &[f32], _args: &[f32]) -> (f32, Vec<f32>) {
    (
        manhattan(x, y, _args),
        (0..x.len()).map(|i| (x[i] - y[i]).signum()).collect(),
    )
}

#[test]
fn generic_layout_matches_python_serial() {
    let mut rng_state = RNG_STATE;
    let mut embedding =
        ndarray::Array2::from_shape_fn((N_VERTICES, 2), |(i, d)| INIT_EMBEDDING[i][d] as f32);
    optimize_layout_generic(
        &mut embedding,
        TailEmbedding::Same,
        HEAD,
        TAIL,
        N_EPOCHS,
        N_VERTICES,
        EPOCHS_PER_SAMPLE,
        A,
        B,
        &mut rng_state,
        1.0,
        1.0,
        5.0,
        manhattan_grad,
        &[],
        false,
    );
    let mut max_err = 0.0f64;
    for i in 0..N_VERTICES {
        for d in 0..2 {
            let got = f64::from(embedding[[i, d]]);
            let want = RESULT[i][d];
            max_err = max_err.max((got - want).abs());
        }
    }
    assert!(max_err < 1e-3, "max abs error {max_err}");
}
